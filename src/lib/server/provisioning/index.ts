/**
 * Replace {{UPPER_SNAKE_CASE}} placeholders in a template string.
 * Only matches UPPER_SNAKE_CASE patterns to avoid colliding with
 * Go template syntax like {{.Status}} used by podman commands.
 */
function replacePlaceholders(template: string, vars: Record<string, string>): string {
  return template.replace(/\{\{([A-Z][A-Z0-9_]*)\}\}/g, (_match, key) => {
    return key in vars ? vars[key] : '';
  });
}

function toBase64(content: string): string {
  return Buffer.from(content).toString('base64');
}

/**
 * A value safe to write into a file that will be `.`-sourced by a shell.
 *
 * `traefik-config.env` is sourced, not parsed, so its values are shell syntax.
 * The tokens and URLs written there are generated by Rudder and contain nothing
 * that needs quoting, but the proxy credentials are typed by a person: a
 * password of `pa"ss\word` written bare produces an unmatched quote, and
 * sourcing the file then fails outright — taking the routing fetch with it, for
 * a reason that appears nowhere near the password field.
 *
 * Single quotes because they suppress every expansion; the only character that
 * cannot appear inside them is the single quote itself, which is closed,
 * escaped and reopened in the usual way.
 */
function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

